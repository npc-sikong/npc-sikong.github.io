export function allRequirementItems() {
  return versionRequirementRecords.flatMap((version) => (
    (version.items || []).map((item) => ({
      ...item,
      version: version.version,
      versionTitle: version.title,
      versionStatus: version.status,
    }))
  ))
}

export function getModuleRequirement(path) {
  const history = allRequirementItems().filter((item) => item.path === path)
  if (!history.length) return null
  return { ...history[history.length - 1], history: [...history].reverse() }
}

export function getModuleChangeType(path) {
  const history = allRequirementItems().filter((item) => item.path === path)
  if (history.length) return history[history.length - 1].changeType
  return null
}

export function getGroupChangeType(groupLabel, childPaths = []) {
  const explicit = [...allRequirementItems()].reverse().find((item) => item.group === groupLabel && item.groupChangeType)
  if (explicit) return explicit.groupChangeType
  const children = childPaths.map(getModuleChangeType).filter(Boolean)
  return children.length ? '改' : null
}
