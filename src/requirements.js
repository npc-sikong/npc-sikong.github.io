function storefrontAmountLogic(moduleName, renderer) {
  if (moduleName === '钱包与资金') return '所有金额均为演示数据。预计到账 = 输入金额 × 演示汇率；兑换手续费后到账 = 输入金额 × 汇率 − 演示手续费；全部提现不得超过当前可提现余额，最小/最大金额按页面提示校验。'
  if (moduleName === '红包与转账') return '红包总扣款 = 红包总金额；固定红包单个金额 = 总金额 ÷ 红包个数；拼手气红包仅保证各领取金额合计等于总额。红包总额上限 3000，流水倍数范围 0–100，退回时间为 0 时不自动退回。所有扣款只更新本地演示余额。'
  if (moduleName === '推广代理') return '演示收益 = 有效流水 × 工资比例；下级工资比例必须低于上级可用比例至少 0.0001。金额与比例只用于页面计算示例。'
  if (moduleName === '哈希游戏') return '单次总投注 = Σ各已选盘口金额；预计返还 = 中奖盘口金额 × 演示赔率；牛牛有效流水按目标规则以投注金额的 1/10 演示计算。最低投注为 1 USDT / 1 TRX / 1 CNY，所有下注只写入本地记录。'
  if (moduleName === '区块彩票') return '彩票总额 = 单注金额 × 注数 × 倍数；追号合计 = Σ各期单期金额 × 当期倍数；冷热、遗漏和中奖额均使用确定性模拟数据，不产生真实投注。'
  if (moduleName === '福利活动' && renderer === 'benefit-lucky5') return '奖票数 = floor（单笔充值折算 CNY ÷ 200）；例如充值 2100 CNY 获得 10 张。奖金按一等奖 10000、二等奖 500、三等奖 100、四等奖 20、五等奖 5 演示，需 1 倍流水。'
  if (moduleName === '记录中心') return '汇总值由当前本地筛选结果计算；总投注为记录金额求和，有效投注和输赢按每条演示记录字段汇总。'
  if (renderer === 'prize') return '历史返奖次数、奖池、备付金和累计派彩均为确定性演示值，不读取真实地址余额。'
  return '本页面不产生真实金额、比例或次数变更；出现的数值均为确定性前端演示数据。'
}

